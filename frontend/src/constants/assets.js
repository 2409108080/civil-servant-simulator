/**
 * 资产目录与财产申报参数。
 *
 * ── 为什么价目表只写一份 ──────────────────────────────────────
 * 「买豪车要 50 万」这件事只在 ASSET_CATALOG 里写一次，事件里**不写价格**，
 * 只写 `buyAsset: { kind: 'car', holder: 'self' }`。
 * 价格写两遍（事件里一个 costMoney、目录里一个 price）迟早会对不上：
 * 改了一处忘了另一处，表现是"选项上写着 50 万，实际扣了 60 万"，
 * 而两边都不报错。钱的事不能靠人记着同步。
 *
 * ── 代持的代价与收益 ─────────────────────────────────────────
 * 亲友代持要额外付 PROXY_FEE_RATE 的手续费（走账、过人情都得花钱），
 * 换来的是**两头都降低被发现的机会**：季度风险减半、申报时不进总数。
 * 但只是降低，不是消除——每次财产申报仍有一定概率被翻出来（见 PROXY_EXPOSE_ODDS）。
 *
 * 为什么代持不能做成"完全查不到"：那样它就是一个纯优解，
 * 玩家永远该代持，「本人名下」这个选项从此没人点，等于白设计了两个选项。
 */

