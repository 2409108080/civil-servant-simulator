/** 危机公关：三个选项的参数 */
/**
 * 危机公关。
 *
 * ── 平事的价与效果随次数递增 ────────────────────────────────
 * 除了硬扛，另外两条路每用一次就贵一分：钱越花越多、效果越来越少，
 * 找人脉的门槛一次比一次高。
 *
 * 为什么只动数值、不动触发条件：危机发作的条件（risk > riskMax）是
 * "组织上盯上你了"这件事本身，跟玩家按过几次平事按钮无关；
 * 把它也做成递增的，等于"平事平得越多，组织上越不来问你"——
 * 方向正好反了，而且会把这条支线变成越用越安全的套利。
 * 递增的应该是**摆平的代价**，不是**被发现的概率**。
 *
 * 下面这几项里，*第一个值就是改动前的值*（moneyCost 5 万 = 第一次的价，
 * moneyRelief 10 = 第一次的效果）。所以 count = 0 时与改动前逐字一致。
 * 递推规则见 game/crisis.js 的 crisisMoneyCostOf / crisisMoneyReliefOf /
 * crisisMgmtGateOf，这里只存刻度。
 */
export const CRISIS = {
  // 花钱平事：第一次 5 万，之后每次 ×1.5，向上取整到万，封顶 50 万
  moneyCost: 50000,
  moneyCostRatio: 1.5,
  moneyCostCap: 500000,
  // 效果：第一次 -10，之后每次少 2 点，封顶 -3
  moneyRelief: 10,
  moneyReliefStep: 2,
  moneyReliefFloor: 3,
  // 动用向上管理人脉：第一次门槛 10 点，之后每次翻倍
  //
  // 为什么用翻倍而不是加一个固定值：向上管理是**有上限的**资源
  // （RESOURCE_LIMITS.mgmt[1] = 100），实测危机发作时它 P25 = 90、中位 100，
  // 基本常年顶格。加固定值（比如每次 +10）的话，一个常年 100 点的玩家
  // 可以找人脉找到天荒地老，门槛根本拦不住任何东西。
  // 翻倍则是 10 → 20 → 40 → 80 → 160：前四次都过得去，
  // 第五次起够不着（160 > 100，而那 100 点还会被每次用掉的 10 点往下压）。
  // 于是一条职业生涯里"找老领导"这件事被限在四次左右——这才叫"人情用一次薄一次"。
  mgmtCost: 10,
  mgmtGateRatio: 2,
  mgmtRelief: 15,
  // 硬扛：一半概率风险再涨，一半概率原地不动；无论哪种，本次提任都告吹。
  // 这一条**不递增**：它是"什么都不做"，没有成本可涨。
  toughRiskGain: 5,
  toughOdds: 0.5
}

/**
 * 走动关系：1 点行动力 + 一笔家产，换风险 -5~10、人缘 +5。
 *
 * 加家产这道成本，是因为只花行动力的话，它在钱多得没处花的局里等于免费，
 * 压风险没有代价，"这季度走不走动"就不成其为一道选择题了。
 *
 * ── 家产的价目**不在这里** ──────────────────────────────────
 * 它按职级递增（科 1 万 / 处 2 万 / 厅 5 万 / 省部 10 万），
 * 收过钱的还要翻倍。取值一律问 assets.js 的 balanceMoneyCostOf()。
 * 那张表放在那边是因为它得按职级分档，而 bandOfLevel 在 promotion.js、
 * assets.js 已经引了它。**这里刻意不再留一份 moneyCost 副本**——
 * 同一笔价钱写两处，迟早改了一处忘了另一处，而钱的事不会报错。
 */
export const BALANCE = {
  apCost: 1,
  riskReliefMin: 5,
  riskReliefMax: 10,
  popularityGain: 5,

  // ── 有案底的人：同一趟走动，压不住多少事 ────────────────────
  // 收过钱的人，人情路子已经窄了，同样一顿饭、同样一笔钱，
  // 换回来的只是一句"再看看"：降幅降到原来的三分之一，人缘也少一些。
  // 这是**文案与手感**上的分档，不是数值上的绞索——别指望它拦住谁。
  //
  // ── 实测：这三档数字全都不是决定性的 ────────────────────────
  // 60 局对照跑下来，涨价（×2 → ×5）、限次（每季 1 次）、降幅（5~10 → 1~3）
  // 三样加起来也只把贪腐流落马率从 11.7% 挪到 10%；把这一段的人缘从 +3
  // 改成 +0，登顶率反而从 16.7% 升到 20%（60 局里两局的差别，就是噪声）。
  // 也就是说，**走动的收益怎么调都无所谓，它压根不是结局的因**。
  //
  // 真正的因是一个记账漏洞（已在 engine.js 的 spendMoney() 修掉）：
  // 走动只扣家产、不记累计支出，于是花掉的每一分钱都从申报差额的分子上
  // 凭空消失——差额就是纪委那本账，所以走动关系实际是一条**洗钱通道**。
  // 修好之后同一个机器人：落马率 10% → 51.7%，登顶率 33.3% → 16.7%。
  // 数字调不动的东西，一行记账改好了。
  recordRiskReliefMin: 1,
  recordRiskReliefMax: 3,
  recordPopularityGain: 3
}

/** 金额千分位。界面上凡是要给玩家看钱的地方都走它，避免各写各的 */
export function formatMoney(amount) {
  const num = Math.round(Number(amount) || 0)
  return num.toLocaleString('zh-CN')
}

/** 取某职级的月薪保底。职级不认识时退回 0，调用方用 max() 兜住即可 */
export function salaryFloorOf(level) {
  return SALARY_BY_LEVEL[level] || 0
}
