/**
 * 事件冷却期：同一个事件被结算之后，多少个季度内不再被抽到。4 个季度 = 一年。
 *
 * ── 为什么是"冷却"而不是"见过就不再抽" ──────────────────────
 * 永久排除的问题不在于它排除得太多，而在于它**排不完**：池子抽干之后
 * 必须有一个兜底支路把旧事件放回来，而那条支路只能在"谁最久没用过"上做文章，
 * 于是它依赖记账顺序。2.5.0 那台复读机就是这条支路失守的结果——实测
 * 每点一次「推进工作」都弹同一条，一局里同一条事件出现 277 次。
 * 冷却期把"回来"变成常规路径而不是兜底路径，就没有这条支路可失守了。
 *
 * ── 为什么是 4 ─────────────────────────────────────────────
 * 一局 36 年、每季约 3 点行动力，一年下来约 12 次抽取。池子 138 条，
 * 4 个季度意味着任意时刻被冷却的约有 12~15 条，占比一成上下——
 * 既足以让"刚刚那件事"不再立刻重来，也不至于把某一档（风险题材的科级料
 * 只有个位数）抽空到要放宽职级。真抽空了也有兜底：先出冷却的先来。
 *
 * 一年在体感上也说得通：同一件事隔一年再遇上，是"又来了"；
 * 隔一个季度再遇上，是"怎么又是这个"。
 */
