      hasInquiryNotice: false,
      // 函询上选了对抗或沉默，下季度直接立案（季末消费掉，只活一个季度）。
      // **入档**：这是一次待执行的处分，不是界面态。不入档的话，
      // 选了"找老领导打招呼"再刷新一下，这件事就过去了。
      inquiryEscalated: false,
      // ── 风声预警（见 game/flee.js）──
      // 那通电话响过没有（只置位不复位）。引擎按事件上的 onceFlag 在结算时置起，
      // 与 hasInquiryNotice 同一套路：一辈子只发生一次的事，不该指望冷却机制兜住。
      // **入档**：不入档的话，接过电话的人刷一下页面，命运就再给他一次通风报信的机会——
