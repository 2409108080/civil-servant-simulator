//        · 清档政策改成"只有主版本变才清"，次版本靠读档补齐兼容（见文件头）。
//        **这一次改动本身就是主版本变化**（2 → 1），所以 2.9.0 的档会被清一次。
//        清的只有我们自己的测试档，无所谓；要紧的是时间点——
//        交到玩家手里之后再动主版本，那就是真抹人家的档了，所以这一刀
