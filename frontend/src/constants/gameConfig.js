      fleeWarned: false,
      // 电话里选了"不走"。下个季度直接立案审查（季末消费掉，只活一个季度）。
      // 与 inquiryEscalated 同类：这是一次待执行的处分，不是界面态。
      // 不入档的话，选了"不走"再刷新一下，这个季度就白过了——
      // 决定书不会来，他可以照常上班、照常走动关系、照常申报。
      fleeRefused: false,
      // 本季度走动关系走了几次。只有有案底的人受上限约束（见 assets.js 的
      // BALANCE_RECORD_QUARTERLY_CAP），季末清零。
      // **入档**：不入档的话，收过钱的人走一次、刷一下页面，计数回零，
