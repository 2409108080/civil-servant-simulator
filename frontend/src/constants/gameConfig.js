      // （60 局模拟落马率 0%），一次不给时又全在 31 岁暴毙（落马率 65%）。
      // 限一次，落马才发生在"第二次"——年龄自然推到中段，
      // 而两次立案之间的那段窗口正好留给了重新攒钱、也就是留给那通电话。
      //
      // 入档：刷新一下就把用过的机会刷新回来，等于无限退赃。
      usedRetreat: false,
      // ── 财产申报的差额：合法收入的**起算点** ──
      // 差额 = 家产 + 名下资产 −（累计合法收入 − 这个起算点）。
      // 没退过赃时它是 0；退赃时被推到当时的累计收入（见 engine 的 surrender），
