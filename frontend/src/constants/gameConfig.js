//        · 跑路的解锁风险线从 70 放到 60（见 game/flee.js——70 实测够不到）。
// 1.9.0：认罪退赃限一次（gameStatus 用 usedRetreat 记账，取代原来的 investigationTier）。
//        老档没有这个字段，读档时会回落到默认值 false，等于把用过的机会还回来——
//        而且是**在已经退过一次赃、钱和风险都已清零之后**还回来，
//        玩家能靠刷新反复洗白。这与 1.7.0 的任职年限是同一类问题，所以照例清档。
// 2.0.0：财产申报的差额从"现金 + 资产 − **累计**合法收入"改成
//        "现金 + 资产 − **最近 4 个季度**合法收入"（gameStatus 新增
//        incomeRecent 与 legalSnap 两个字段，见 constants/assets.js）。
// 2.1.0：终局机制的一次大修，四件事一起改，都改的是"同一份存档会走向哪个结局"：
//        · 差额公式定稿为 `家产 + 资产 − (累计合法收入 − 退赃起算点)`
//          （gameStatus 新增 retreatLegalBaseline，取代 incomeRecent / legalSnap）。
//          2.0.0 那版减的是"最近 4 季收入"，被减数是存量、减数是流量，
//          把**清廉流**打死了——实测"严格不贪"画像落马率 65%，
//          同一颗种子下 1.9.0 是 0%。新写法下清官的差额恒为 0，
//          而赃款逐期累积，退赃后起点被推高、新账重新算起；
//        · 单笔贪腐金额按职级封顶（科级 10 万 / 处级 50 万 / 厅级 300 万，
//          在事件池出口兜，见 game/eventPool.js 的 capIllicit）；
//        · 财产申报红线按职级分档（科级 50 万 / 处级 100 万 / 厅级 300 万）；
//        · 新增「养鱼期」：头 8 个季度只约谈不立案（见 assets.js）。
//        以上任何一条都会让老存档算出不同的差额与不同的立案时点，所以照例清档。
// 2.2.0：贪腐流节奏的一刀，两个数一起动，所以照例清档：
//        · 立案红线整条 ×3（科级 50→150 万 / 处级 100→300 万 / 厅级 300→900 万）；
//        · 单笔贪腐封顶整体 ×0.4（科级 10→4 万 / 处级 50→20 万 / 厅级 300→120 万）。
//        起因：见钱就收的玩法落马率 96.7%、平均 33.4 岁，伸手即死，
//        玩家建立不起"越陷越深"的体感。目标是 40~60% / ≥45 岁。
//        注意方向——**降线（A）和扩事件池（B）都是踩油门**，实测落马率
//        反而升到 100%、年龄掉到 30。能把年龄往后推的只有抬线 + 收紧封顶：
//        线决定"攒多久算够"，封顶决定"一笔能攒多少"，两个必须成对动。
// 2.3.0：走动关系从"一律 1 万"改成按职级递增、有案底翻倍，所以照例清档：
//        · player 新增 hasIllicitRecord（收过钱没有，只置位不复位）；
//        · 家产门槛改成科 1 万 / 处 2 万 / 厅 5 万 / 省部 10 万，
//          有案底再 ×5（见 assets.js 的 BALANCE_COST_BY_BAND）；
//        · 有案底的人**每季度最多走动 1 次**（gameStatus 新增 balanceThisQuarter）；
//        · 带案底的降幅分档（风险 -1~3、人缘 +3，见 money.js 的 BALANCE）。
//          实测这三条**都没咬住**：涨价 ×2 时落马率 20%、×5 时 11.7%，
//          降幅砍到 1/3 后是 10%——三条改动都没把贪腐流拉回来。
//        · **真正的原因是一个记账漏洞**（本版修掉）：走动关系只扣家产、
//          没记进累计支出。财产申报的差额是 `家产 + 资产 + 累计支出 − 合法收入`，
//          出账不记账，花掉的钱就凭空从分子上消失——**走动关系成了一条洗钱通道**，
//          带案底的人每局走掉 ¥400 万差额。这也解释了为什么涨价反而更安全：
//          涨的是洗钱通道的吞吐量。现在所有出账统一走 engine.js 的 spendMoney()，
//          事件 costMoney 与危机公关的平事钱同时补上（buyAsset 不走它——
//          钱变成了车房，本来就在分子里，再记一次就是重复计算）。
//        · **新增提任廉政审查**：有案底的人提任时多掷一道关（promotion.js 的
//          auditPassOddsOf），未通过则**挂起 6 个季度**（gameStatus 新增
//          auditHoldUntil），期间不受理提任——不是落马。
//          清廉流一次都不掷（实测 60 局、四个画像共 0 次），所以"不受影响"
//          是机制上的保证，不是统计上的巧合。
//        · **删掉"退一半"整条支线**（game/refund.js 连同 refundPending 字段）。
//          它与退赃、走动关系在玩家直觉里是同一件事，三者的边界说不清。
//        老档读进来 hasIllicitRecord 会回落到默认值 false，而 deepMerge
//        补的这个 false 是**错的**——一个已经收过钱、甚至退过赃的存档
//        会拿到清廉流的折扣价，走动成本凭空减半。
//        这是"读档时补默认值反而把新规则绕过去"的又一例，
//        与 1.9.0 的 usedRetreat 同类，所以照例清档重开。
// 2.4.0：廉政审查加挂起期（gameStatus 新增 auditHoldUntil），存档契约变了。
//        只看"审查未通过就本次否决"是拦不住的：贪腐流连续很多季都达标，
//        每季重掷一次，0.35^9 ≈ 0.0001，等于没有这道关。
//        挂起 6 季之后，"会走动"与"不走动"两个画像的登顶率才同时进 5~10%。
//        老档没有这个字段，deepMerge 会补 0——补 0 的意思是"不挂起"，
//        即一个正在挂起期的存档读进来就解除挂起了。虽然 2.3.0 从未发布过、
//        世上没有这类存档，但**契约变了就照例递增版本**，不靠"这次没人受影响"赌。
// 2.5.0：函询通知书改成一次性事件（gameStatus 新增 hasInquiryNotice 与
//        inquiryEscalated），存档契约变了。
//        起因是一个复读机：玩家账上钱一多，每点一次「推进工作」就弹同一份
//        函询通知书。查下来是**两个毛病叠在一起**——
//        · 事件池的冷却重置挑"最久没用过"的那条，靠的是 usedEventIds 的**顺序**，
//          而界面那边记已用事件时写的是"已经有了就不再记"，于是被重复抽到的事件
//          下标永远停在第一次的位置。整池抽干后，每次重置都挑中同一条。
//          实测把全池 138 条都标成已用过，连抽 10 次出来的是同一个 id。
//          修法是记的时候从原位摘掉再追加到末尾（见 GameMain 的 onChoose），
//          读的时候按最后一次出现的下标取（见 eventPool.js 的 drawEvent）；
//        · 函询这种事在剧情上本来就是一次性的，不该指望避重机制兜住它。
//          新增 onceFlag 标签，标记位由引擎在结算时置起（见 engine.js 的 applyOption）。
//        老档读进来 hasInquiryNotice 会回落到默认值 false，等于"这局还没发过函询"——
//        一个已经被函询过、甚至已经对抗过的存档，读档后可以重新再收到一份。
//        与 1.9.0 的 usedRetreat 同类，所以照例清档重开。
// 2.6.0：事件避重从"见过就永久排除"改成"冷却 4 个季度"
//        （gameStatus 的 usedEventIds 换成 eventCooldown），存档契约变了。
//        起因同 2.5.0 那台复读机，但 2.5.0 只是把记账顺序修对了，
//        机制本身仍然依赖"一边写、一边读"的配合：永久排除一旦把池子抽干，
//        就必须有一个"重置冷却"的兜底支路，而那条支路只能靠记账顺序判谁最久
//        没用过——顺序一失守就退回复读机。冷却期没有这条支路：
//        任何事件最多消失一年，一年后自然回来，不依赖任何记账顺序。
//        老档读进来 eventCooldown 会回落到空对象，等于"所有事件都可用"——
//        一个刚被反复抽过的存档，读档后同一件事会立刻回来。
// 2.7.0：风险触顶的结局按"有没有伸手"分成两个（见 engine.js 的 ENDINGS）
//        ——收过钱的仍是纪委监委留置，一分钱没贪的改判【免职闲赋】。
//        同时 gameStatus 新增 crisisHandledCount / crisisFavorCount，
//        平事的价钱与效果开始按次数递增（见 game/crisis.js）。
//        为什么要清档：同一份存档在旧规则下判留置、在新规则下判免职，
//        结局都不一样了；而且旧档里没有那两个计数，
//        读进来会回落成 0，等于"平事的价码从头算"——一个已经花过三次钱的人
//        刷新一下就能按头一回的 5 万再平一次事。与 2.5.0、2.6.0 同例，清档重开。
// 2.8.0：到顶即退休不再是"到了顶点就善终"（见 engine.js 的 checkGameOver）
//        ——账上还有赃款的人登顶，判【立案审查调查】，不再是光荣退休。
//        同一份存档在旧规则下"政声卓著"、在新规则下进决定书，结局不一样，
//        所以照例清档重开。另：职务与单位现在一起随职级上行
//        （见 constants/positions.js 的 ORGANS），老档里"市档案局 + 省档案馆馆长"
//        这种错位由读档修复静默改正，不单独构成清档的理由。
// 2.9.0：主动跑路整条撤掉，改成一次性事件「一个很久没打来的电话」
//        （gameStatus 新增 fleeWarned / fleeRefused，见 game/flee.js）。
//        · 工作台上那个「卷款跑路」按钮没了。它把跑路做成了一条**可以提前规划**
//          的退路：按钮一亮，玩家就围着它攒钱、卡着风险线走，而这条路要的是
//          "走投无路时有人递来一张船票"。现在只有一通电话能开这个口子。
//        · 触发条件从"赃款 500 万 + 风险 60"降到"300 万 + 40"——按钮要经得起
//          反复看见所以得够高，电话一辈子只响一次，响得越晚越像彩蛋。300 万
//          正是厅级立案线，与"有人开始认真看你账本"是同一件事。
//        · 成功率不再是定值 0.8：0.2 起，赃款每多 100 万加 20 个点，封顶 0.8；
//          铺路先烧掉三成赃款（成不成都不退）。选了"不走"的人，
//          下个季度**直接立案审查**，不再走财产申报。
//        为什么照例清档：同一份 2.8.0 存档，一个攒到 500 万、风险 60 的玩家
//        随时可以按按钮拿 80% 走掉；在 2.9.0 他只能等那通电话，拿到的还是
//        按 300 万起算的那档成功率。同一份存档走向不同结局，就照例清档重开。
// 1.0.0：**发行版**。相对 2.9.0 没有动任何契约、任何数值，只有两件事：
